import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createUiReviewServer, reviewChromium, reviewOutput } from "./ui-review-runtime.mjs";

const output = reviewOutput(mkdtempSync(join(tmpdir(), "echo-continuation-")));
const server = await createUiReviewServer(0);
const base = `http://127.0.0.1:${server.httpServer.address().port}/__ui-review?surface=workbench&platform=mac&continuation=1`;
let browser;
try {
  browser = await (await reviewChromium()).launch({headless:true,executablePath:process.env.CHROME_BIN || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"});
  const page = await browser.newPage({viewport:{width:1280,height:860}});
  const errors = []; page.on("pageerror",error => errors.push(error.message));
  const composer = page.locator(".echo-composer__input");
  const continueAtSecondTurn = async () => {
    await page.locator('[data-msg-id="continuation-answer-1"]').getByRole("button",{name:"更多回复操作"}).click();
    await page.getByRole("menuitem",{name:"在新对话中继续",exact:true}).click();
    await page.locator(".conversation-origin__source").waitFor();
  };
  await page.goto(`${base}&state=complete`);
  await composer.fill("原对话未发送内容");
  await continueAtSecondTurn();
  assert.equal(await composer.inputValue(),"");
  assert.equal(await page.locator("#conversation-inherited-history").isVisible(),false);
  assert.equal(await page.locator(".msg-wrap:visible").count(),0);
  await page.screenshot({path:join(output,"child-collapsed.png")});
  await page.getByRole("button",{name:/已继承 2 轮上下文/}).click();
  assert.equal(await page.locator(".msg-wrap:visible").count(),4);
  assert.equal(await page.getByText("后续的独立页面方案：",{exact:false}).count(),0,"later turns must not be copied");
  const requests = await page.evaluate(() => window.workbenchCalls.filter(call => call.command === "session_continue"));
  assert.equal(requests.length,1);
  assert.equal(requests[0].args.targetPromptIndex,1);
  assert.equal(requests[0].args.sourcePromptId,"continuation-turn-1");
  await composer.fill("接下来探索弹窗方案");
  await page.locator(".conversation-origin__link").click();
  await page.locator('[data-msg-id="continuation-answer-1"].msg-wrap--jump-target').waitFor();
  assert.equal(await composer.inputValue(),"原对话未发送内容");
  assert.equal(await page.locator(".msg-wrap").count(),6,"source transcript is unchanged");
  await page.locator(".conversation-continuations summary").click();
  await page.screenshot({path:join(output,"source-return.png")});
  await page.locator(".conversation-continuations button").click();
  await page.locator(".conversation-origin__source").waitFor();
  assert.equal(await composer.inputValue(),"接下来探索弹窗方案");
  await page.setViewportSize({width:1024,height:760});
  await page.evaluate(() => { document.documentElement.dataset.theme="dark"; document.documentElement.style.fontSize="20px"; });
  await page.screenshot({path:join(output,"child-narrow-large.png")});
  const geometry = await page.evaluate(() => ({overflow:document.documentElement.scrollWidth>innerWidth+1,
    originOverflow:document.querySelector('.conversation-origin').scrollWidth>document.querySelector('.conversation-origin').clientWidth+1}));
  assert.equal(geometry.overflow,false); assert.equal(geometry.originOverflow,false);
  // Collapsing inherited history closes search instead of retaining invisible hits.
  await page.getByRole("button",{name:"任务操作",exact:true}).click();
  await page.getByRole("menuitem",{name:/查找当前会话/}).click();
  await page.getByRole("textbox",{name:"查找",exact:true}).fill("验证码");
  await page.locator(".find-hit").first().waitFor();
  await page.getByRole("button",{name:/已继承 2 轮上下文/}).click();
  assert.equal(await page.getByRole("textbox",{name:"查找",exact:true}).count(),0);
  assert.equal(await page.locator(".find-hit").count(),0);
  await page.getByRole("button",{name:"任务操作",exact:true}).click();
  await page.getByRole("menuitem",{name:/查找当前会话/}).click();
  assert.equal(await page.locator("#conversation-inherited-history").isVisible(),true);
  await page.keyboard.press("Escape");
  await page.evaluate(async () => {const {useSessionsStore}=await import("/src/stores/sessions-store.ts"); useSessionsStore.getState().upsert({sessionId:"review-conversation",title:"原会话新名称"});});
  await page.getByRole("button",{name:/返回“原会话新名称”/}).count();
  assert.equal(await page.locator(".conversation-origin__link").textContent(),"原会话新名称");
  await page.evaluate(async () => {const {useSessionsStore}=await import("/src/stores/sessions-store.ts"); useSessionsStore.getState().remove("review-conversation");});
  await page.getByText("· 原对话已删除").waitFor();
  assert.equal(await page.locator(".conversation-origin__link").count(),0);
  assert.equal(await page.locator(".msg-wrap:visible").count(),4);

  await page.setViewportSize({width:1280,height:860});
  await page.goto(`${base}&state=complete&rejectContinuation=1`);
  await page.getByRole("button",{name:"任务操作",exact:true}).click();
  await page.getByRole("menuitem",{name:"在新对话中继续",exact:true}).click();
  await page.getByRole("button",{name:"重试创建"}).waitFor();
  await page.getByRole("button",{name:"重试创建"}).click();
  await page.locator(".conversation-origin__source").waitFor();
  const retried = await page.evaluate(() => window.workbenchCalls.filter(call => call.command === "session_continue"));
  assert.equal(retried.length,2); assert.equal(retried[0].args.requestId,retried[1].args.requestId);
  await page.goto(`${base}&state=complete&rejectContinuation=1&delayRefresh=1`);
  await composer.fill("刷新历史时仍需保留的草稿");
  await page.getByRole("button",{name:"任务操作",exact:true}).click();
  await page.getByRole("menuitem",{name:"在新对话中继续",exact:true}).click();
  await page.getByRole("button",{name:"刷新原对话",exact:true}).click();
  await page.getByText("正在刷新原对话…",{exact:true}).waitFor();
  assert.equal(await composer.isDisabled(),false);
  await composer.press("Enter");
  assert.equal(await page.evaluate(() => window.workbenchCalls.some(call=>call.command === "review_send")),false);
  await page.evaluate(() => window.releaseRefresh());
  await page.getByText("正在刷新原对话…",{exact:true}).waitFor({state:"detached"});
  assert.equal(await composer.inputValue(),"刷新历史时仍需保留的草稿");
  assert.equal(await page.locator(".msg-wrap").count(),6);
  await page.getByRole("button",{name:"任务操作",exact:true}).click();
  await page.getByRole("menuitem",{name:"在新对话中继续",exact:true}).click();
  await page.locator(".conversation-origin__source").waitFor();
  const refreshed = await page.evaluate(() => window.workbenchCalls.filter(call => call.command === "session_continue"));
  assert.equal(refreshed.length,2);
  assert.notEqual(refreshed[0].args.requestId,refreshed[1].args.requestId);
  await page.goto(`${base}&state=complete&delayContinuation=1`);
  await page.getByRole("button",{name:"任务操作",exact:true}).click();
  await page.getByRole("menuitem",{name:"在新对话中继续",exact:true}).click();
  await page.getByText("正在创建新对话…",{exact:true}).waitFor();
  assert.equal(await page.getByRole("button",{name:"重新生成",exact:true}).isDisabled(),true);
  assert.equal(await composer.isDisabled(),false,"the draft remains editable while creation is pending");
  assert.equal(await page.evaluate(() => window.workbenchCalls.some(call=>call.command === "rewind_execute")),false);
  await page.evaluate(() => window.releaseContinuation());
  await page.locator(".conversation-origin__source").waitFor();
  await page.goto(`${base}&state=running`);
  await page.getByRole("button",{name:"任务操作",exact:true}).click();
  assert.equal(await page.getByRole("menuitem",{name:"在新对话中继续",exact:true}).isDisabled(),true);
  assert.deepEqual(errors,[]);
  writeFileSync(join(output,"evidence.json"),JSON.stringify({geometry,errors,checks:["inclusive history cut","collapsed inheritance","source navigation","both drafts preserved","child navigation","source rename and deletion","retry request identity","stale source refresh preserves draft and allows a new target","busy guard","pending copy excludes regeneration","collapsed search has no invisible hits"]},null,2));
  console.log(`Passed conversation continuation interactions and layout; evidence: ${output}`);
} finally {await browser?.close(); await server.close();}
