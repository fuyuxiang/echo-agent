import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createUiReviewServer, reviewChromium, reviewOutput } from "./ui-review-runtime.mjs";

const output = reviewOutput(mkdtempSync(join(tmpdir(), "echo-attachment-preview-")));
const server = await createUiReviewServer(0, { fixture: "/scripts/fixtures/attachment-preview-review.tsx" });
const base = `http://127.0.0.1:${server.httpServer.address().port}/__ui-review`;
let browser;
const evidence = [];
try {
  browser = await (await reviewChromium()).launch({ headless: true, executablePath: process.env.CHROME_BIN || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
  for (const [width, height] of [[1440, 900], [1024, 680], [720, 640], [360, 640]]) for (const theme of ["light", "dark"]) for (const font of [13, 18]) {
    const page = await browser.newPage({ viewport: { width, height } });
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto(`${base}?theme=${theme}&font=${font}&many`, { waitUntil: "networkidle" });
    const input = page.locator(".echo-composer__input");
    await input.waitFor();
    assert.equal(await page.getByRole("listitem").count(), 20);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.equal(await page.evaluate(() => window.__attachmentCalls.some(call => call.command === "attachment_preview_data")), false);
    await input.fill("逐项核对内容，关闭预览后继续编辑。");
    const trigger = page.getByRole("button", { name: "预览附件 界面截图.png" });
    await trigger.click();
    const dialog = page.getByRole("dialog", { name: "界面截图.png" });
    await dialog.waitFor();
    const image = dialog.getByRole("img", { name: "界面截图.png" });
    await image.evaluate(image => image.complete && image.naturalWidth ? undefined : new Promise(resolve => image.addEventListener("load", resolve, { once: true })));
    assert.equal(await image.evaluate(image => image.naturalWidth), 1600, "Preview uses a thumbnail instead of the original");
    const bounds = await dialog.boundingBox();
    assert(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= width + 1 && bounds.y + bounds.height <= height + 1);
    await dialog.getByRole("button", { name: "原始大小", exact: true }).click();
    assert.equal(await image.evaluate(image => Math.round(image.getBoundingClientRect().width)), 1600);
    await dialog.getByRole("button", { name: "适应窗口", exact: true }).click();
    assert(await image.evaluate(image => image.getBoundingClientRect().width <= image.closest(".attachment-preview__stage").clientWidth));
    await page.screenshot({ path: join(output, `image-${width}-${theme}-${font}.png`) });
    await page.keyboard.press("Escape");
    assert.equal(await page.getByRole("dialog").count(), 0);
    assert(await trigger.evaluate(element => element === document.activeElement));
    assert.equal(await input.inputValue(), "逐项核对内容，关闭预览后继续编辑。");
    await page.getByRole("button", { name: "预览附件 需求说明.md" }).click();
    await page.getByRole("dialog").getByRole("heading", { name: "需求说明", exact: true }).waitFor();
    await page.getByRole("button", { name: "下一个附件" }).click();
    await page.getByRole("dialog").getByText("用户在发送前确认文件内容，关闭预览后继续编辑草稿。", { exact: true }).waitFor();
    assert.equal(await page.getByRole("dialog").locator('[contenteditable="true"]').count(), 0);
    if (width === 360) await page.screenshot({ path: join(output, `word-${width}-${theme}-${font}.png`) });
    await page.getByRole("button", { name: "下一个附件" }).click();
    await page.getByRole("dialog").getByRole("cell", { name: "12000", exact: true }).waitFor();
    await page.getByRole("button", { name: "下一个附件" }).click();
    await page.getByRole("dialog").locator("iframe[src^='data:application/pdf']").waitFor();
    await page.screenshot({ path: join(output, `file-${width}-${theme}-${font}.png`) });
    await page.keyboard.press("Escape");
    await page.screenshot({ path: join(output, `composer-${width}-${theme}-${font}.png`) });
    await input.fill("长提示的完整编辑与核对。".repeat(50));
    await page.getByRole("button", { name: "展开编辑", exact: true }).click();
    const editor = page.getByRole("textbox", { name: "完整输入内容" });
    await editor.fill("长提示的完整编辑与核对。".repeat(50) + "\n已核对");
    const editorBounds = await page.getByRole("dialog").boundingBox();
    assert(editorBounds.x >= 0 && editorBounds.y >= 0 && editorBounds.x + editorBounds.width <= width + 1 && editorBounds.y + editorBounds.height <= height + 1);
    if (width === 360) await page.screenshot({ path: join(output, `draft-${width}-${theme}-${font}.png`) });
    await page.getByRole("button", { name: "完成编辑", exact: true }).click();
    assert((await input.inputValue()).endsWith("已核对"));
    await input.fill("逐项核对内容，关闭预览后继续编辑。");
    if (width === 1440 && font === 13 && theme === "light") {
      await page.getByRole("button", { name: "发送", exact: true }).click();
      await page.getByRole("button", { name: "打开附件 界面截图.png" }).click();
      await page.getByRole("dialog").waitFor();
      await page.keyboard.press("Escape");
      await page.getByRole("button", { name: "编辑并重新发送" }).click();
      await page.getByRole("button", { name: "预览附件 界面截图.png" }).waitFor();
      assert.equal(await page.getByRole("list", { name: "待发送附件" }).getByRole("listitem").count(), 20);
      await page.getByRole("button", { name: "预览附件 界面截图.png" }).click();
      await page.getByRole("dialog").waitFor();
      await page.keyboard.press("Escape");
      await page.getByRole("button", { name: "切换任务", exact: true }).click();
      assert.equal(await page.getByRole("button", { name: "预览附件 另一任务.txt" }).count(), 1);
    }
    assert.deepEqual(errors, []);
    evidence.push({ width, height, theme, font, bounds });
    await page.close();
  }
  const page = await browser.newPage({ viewport: { width: 720, height: 640 } });
  await page.goto(`${base}?error=read`, { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "预览附件 界面截图.png" }).click();
  await page.getByRole("dialog").getByRole("alert").filter({ hasText: "已不存在" }).waitFor();
  await page.getByRole("button", { name: "重新加载", exact: true }).click();
  await page.getByRole("dialog").getByRole("alert").filter({ hasText: "已不存在" }).waitFor();
  await page.getByRole("button", { name: "用系统应用打开", exact: true }).click();
  await page.waitForFunction(() => window.__attachmentCalls.some(call => call.command === "open_path"));
  await page.screenshot({ path: join(output, "read-error.png") });
  await page.keyboard.press("Escape");
  assert.equal(await page.getByRole("listitem").count(), 6);
  await page.close();
  writeFileSync(join(output, "review.json"), JSON.stringify(evidence, null, 2));
  console.log(`Passed ${evidence.length} attachment layouts, original-image zoom, Markdown/Word/sheet/PDF, Escape/focus, send and edit/resend. Evidence: ${output}`);
} finally { await browser?.close(); await server.close(); }
